#!/usr/bin/env python3
"""Write src/sgl.def: the SGL.DLL export table.

The exports copy the last SGL.DLL Matrox shipped for the m3D (4.1.1.5),
listed in src/sgl_exports_4115.txt: the same 142 names at the same ordinals.
That release numbered its exports alphabetically. It did not use the order in
Imagination's ordinals.h, which belongs to an earlier, ordinal-only scheme.
Any other function sgl.h declares is exported by name only, after those.
"""
import os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

shipped = []
for line in open(os.path.join(root, 'src/sgl_exports_4115.txt')):
    line = line.strip()
    if line and not line.startswith('#'):
        num, name = line.split()
        shipped.append((int(num), name))

hdr = open(os.path.join(root, 'third_party/powervr-series1/sgl.h'), encoding='latin-1').read()
hdr = re.sub(r'/\*.*?\*/', '', hdr, flags=re.S)
hdr = hdr[hdr.index('API_START(SGL)'):]
known = {n for _, n in shipped}
extra = [n for n in re.findall(r'API_FN\s*\(\s*[^,]+?,\s*(\w+)\s*,', hdr) if n not in known]

lines = ['; Generated by tools/gen_def.py - do not edit.', 'LIBRARY SGL', 'EXPORTS']
lines += ['\t%s @%d' % (name, num) for num, name in shipped]
if extra:
    lines.append('; Declared in sgl.h but not exported by SGL.DLL 4.1.1.5: by name only.')
    lines += ['\t%s' % n for n in extra]
open(os.path.join(root, 'src/sgl.def'), 'w').write('\n'.join(lines) + '\n')
print('%d exports (%d as in 4.1.1.5, %d by name only)' % (len(shipped) + len(extra), len(shipped), len(extra)))
