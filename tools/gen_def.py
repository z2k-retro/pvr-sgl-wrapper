#!/usr/bin/env python3
"""Write src/sgl.def: the SGL.DLL export table.

Every function in ordinals.h is exported by name at its original ordinal.
Functions that sgl.h declares but ordinals.h leaves out (later additions such
as sgltri_lines and sgl_get_ini_int) are exported by name only. Games that
load SGL.DLL themselves, like Unreal's SGLDrv.dll, look functions up by name,
and Unreal asks for some of these."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'third_party/powervr-series1/ordinals.h'), encoding='latin-1').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
body = src[src.index('TOPSTRING\n'):]
ents = re.findall(r'\b([YZ])FUNCTION\(\s*(\w+)\s*,\s*(\d+)', body)
lines = ['; Generated by tools/gen_def.py from ordinals.h - do not edit.',
         'LIBRARY SGL', 'EXPORTS']
for kind, name, num in ents:
    lines.append('\t%s @%s' % (name, num))
hdr = open(os.path.join(root, 'third_party/powervr-series1/sgl.h'), encoding='latin-1').read()
hdr = re.sub(r'/\*.*?\*/', '', hdr, flags=re.S)
hdr = hdr[hdr.index('API_START(SGL)'):]
known = {n for _, n, _ in ents}
extra = [n for n in re.findall(r'API_FN\s*\(\s*[^,]+?,\s*(\w+)\s*,', hdr) if n not in known]
if extra:
    lines.append('; In sgl.h but not ordinals.h: exported by name only.')
    lines += ['\t%s' % n for n in extra]
open(os.path.join(root, 'src/sgl.def'), 'w').write('\n'.join(lines) + '\n')
print('%d exports (%d by name only)' % (len(ents) + len(extra), len(extra)))
